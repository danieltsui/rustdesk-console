// A stored choice always wins, including a value set by the language switcher.
// Otherwise Traditional Chinese (Hong Kong, Taiwan, Macau, or an explicit Hant
// tag) maps to zh-HK, and Simplified Chinese maps to zh-CN. A bare `zh` tag is
// not forced to Simplified Chinese.
export function mapChineseLocale(tag: string): "zh-HK" | "zh-CN" | null {
  const normalized = tag.trim().replace(/_/g, "-");
  if (/^zh-(?:HK|TW|MO|Hant)(?:-|$)/i.test(normalized)) return "zh-HK";
  if (/^zh-(?:CN|SG|Hans)(?:-|$)/i.test(normalized)) return "zh-CN";
  return null;
}

export function resolveConsoleLang(
  stored: string | null | undefined,
  languages: readonly string[],
): string {
  if (stored) return stored;
  for (const tag of languages) {
    const chinese = mapChineseLocale(tag);
    if (chinese) return chinese;
    if (/^en(?:-|$)/i.test(tag.trim().replace(/_/g, "-"))) return "en";
  }
  return "en";
}

function detectLang(): string {
  const stored =
    typeof localStorage !== "undefined" ? localStorage.getItem("lang") : null;
  const languages =
    typeof navigator !== "undefined"
      ? navigator.languages?.length
        ? [...navigator.languages]
        : [navigator.language].filter(Boolean)
      : [];
  return resolveConsoleLang(stored, languages);
}

i18n.on("languageChanged", (language) => {
  if (typeof document !== "undefined") {
    document.documentElement.lang = language;
  }
});

void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: en },
    "zh-CN": { translation: zhCN },
    "zh-HK": { translation: zhHK },
  },
  lng: detectLang(),
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

